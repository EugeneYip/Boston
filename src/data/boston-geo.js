/**
 * Hand-authored geography of Boston.
 *
 * Everything here is real-world lat/lon. Nothing downstream may invent world
 * coordinates; it all flows through `geo()` in src/core/Geo.js.
 *
 * Boston is not a grid, and the whole character of the place is in that
 * irregularity — the 17th-century cowpaths of downtown, the medieval North End
 * lanes, Beacon Hill's tangle on the side of a real hill, and then the one
 * planned exception: the Back Bay, filled in the 1850s as a rigid orthogonal
 * grid with alphabetical cross streets. Those are authored differently on
 * purpose: Back Bay is generated from an exact rotated frame (because that is
 * literally how it was surveyed), everything else is traced by hand.
 */
import { unGeo } from '../core/Geo.js';

// ---------------------------------------------------------------------------
// Back Bay: a surveyed grid, so generate it from a frame instead of hand-typing
// 60 near-identical coordinates that would drift out of parallel.
// Frame anchored at Arlington St x Commonwealth Ave, axis along Comm Ave.
// ---------------------------------------------------------------------------
// Fitted so the grid lands on the real Public Garden corners, Copley Square and
// Mass Ave x Comm Ave simultaneously (they disagree by ~50 m in the sources;
// this is the least-squares compromise).
const BB_OX = -452.5;                 // world x of Arlington x Comm Ave
const BB_OZ = 187.6;                  // world z of same
const BB_BEARING = 251.5 * Math.PI / 180;  // Comm Ave, heading west-southwest
const BB_UX = Math.sin(BB_BEARING);        // unit vector along Comm Ave (westward)
const BB_UZ = -Math.cos(BB_BEARING);
const BB_VX = -BB_UZ;                      // perpendicular, toward the Charles
const BB_VZ = BB_UX;

/** Back Bay grid coordinate -> [lat, lon]. u = metres west along Comm Ave from
 *  Arlington, v = metres toward the Charles from the Comm Ave centreline. */
export function bb(u, v) {
  const x = BB_OX + BB_UX * u + BB_VX * v;
  const z = BB_OZ + BB_UZ * u + BB_VZ * v;
  const ll = unGeo(x, z);
  return [ll.lat, ll.lon];
}

/** Straight Back Bay street: constant v, u from a to b. */
const bbLong = (v, u0, u1, n = 6) => {
  const p = [];
  for (let i = 0; i <= n; i++) p.push(bb(u0 + (u1 - u0) * (i / n), v));
  return p;
};
/** Straight Back Bay cross street: constant u, v from a to b. */
const bbCross = (u, v0, v1, n = 4) => {
  const p = [];
  for (let i = 0; i <= n; i++) p.push(bb(u, v0 + (v1 - v0) * (i / n)));
  return p;
};

